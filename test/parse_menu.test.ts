import ex from '../src/protocol/examples.json';
import { isSceneSnapshot, type SceneSnapshot } from '../src/protocol/index';
import fx from '../fixtures/replay_village.json';
import { Directory } from '../src/directory';
import { buildMenu } from '../src/menu';
import { parseInput, type UiAction } from '../src/parse';
import { assert, done, suite } from './helpers';

const snaps = (fx.steps as any[]).filter(s => s.message.kind === 'snapshot').map(s => s.message.snapshot as SceneSnapshot);
const village = snaps[0], town = snaps[1];
assert(isSceneSnapshot(village) && isSceneSnapshot(town), 'fixture snapshots are valid');

const dir = new Directory(null);
dir.learn(village);
const ctx = { findNpc: (q: string) => dir.findNpc(q), findMap: (q: string) => dir.findMap(q) };
const goalOf = (a?: UiAction | null) => (a && a.kind === 'NAV' ? JSON.stringify(a.goal) : null);
const cmdOf = (a?: UiAction | null) => (a && a.kind === 'COMMAND' ? a.command : null);

suite('scene menu from a real snapshot');
const menu = buildMenu(village, dir.knownElsewhere('10001'));
const sec = (k: string) => menu.find(m => m.key === k)!;
assert(sec('talk').items.length > 10 && sec('talk').items.every(i => i.action?.kind === 'NAV'), '對話：NPC 清單 → 自動導航並對話');
assert(sec('talk').items.every(i => i.action?.kind === 'NAV' && i.action.goal.kind === 'NPC' && i.action.goal.talk), '對話項目都會在抵達後對話');
assert(sec('talk').items.some(i => i.label === '阿爾') && !sec('talk').items.some(i => i.label.includes('貓')), 'animals are not in the 對話 row');
assert(sec('animals').items.length > 0, 'animals listed separately');
assert(sec('goto').items.length > 3 && sec('goto').items.every(i => i.action?.kind === 'NAV' && i.action.goal.kind === 'MAP'), '前往：出口 → 導航到目標地圖');
const grocery = sec('goto').items.find(i => i.label === '雜貨店')!;
assert(grocery.action?.kind === 'NAV' && grocery.action.goal.kind === 'MAP' && typeof grocery.action.goal.mapId === 'string', 'exit item targets the exit\'s destination map');
assert(sec('gather').items.length === 0 && sec('gather').emptyText.includes('尚未提供'), '採集：資料不可得時明說，不當成「本區無」');
assert(sec('nearby').items.length === 0 && sec('nearby').emptyText.includes('尚未提供'), '附近可採：同上');
assert(sec('known').items.some(i => i.label === '村長傑夫' && i.hint === '市鎮中心'), '已知地點：預設就知道村長傑夫在市鎮中心');
assert(buildMenu(ex.snapshot.snapshot as SceneSnapshot).length === 6, 'example snapshot builds a menu too');
dir.learn(town);
const townMenu = buildMenu(town, dir.knownElsewhere('20010'));
assert(townMenu.find(m => m.key === 'talk')!.items.some(i => i.label === '村長傑夫'), 'town center menu lists 村長傑夫');

suite('free text -> the same actions as the menu');
const act = (t: string, snap: SceneSnapshot | null = town) => { const r = parseInput(t, snap, ctx); return r.ok ? r.action : null; };
const chiefItem = townMenu.find(m => m.key === 'talk')!.items.find(i => i.label === '村長傑夫')!;
assert(goalOf(act('前往 村長')) === goalOf(chiefItem.action), '前往 村長 == clicking 村長傑夫 (navigate + talk)');
assert(goalOf(act('對話　村長傑夫')) === goalOf(chiefItem.action), '全形空白也可');
assert(goalOf(act('去 村長')) === goalOf(chiefItem.action), '去 村長');
assert(cmdOf(act('talk 村長傑夫'))?.type === 'TALK_TO_NPC', 'talk <名> = raw TALK_TO_NPC (no walking)');
const g = parseInput('前往 雜貨店', village, ctx);
assert(g.ok && goalOf(g.action) === goalOf(sec('goto').items.find(i => i.label === '雜貨店')!.action), '前往 <出口名> == clicking the exit');
const cross = parseInput('前往 村長', village, ctx);
assert(cross.ok && cross.action.kind === 'NAV' && cross.action.goal.kind === 'NPC' && cross.action.goal.query === '村長傑夫', '前往 村長 from the village resolves through the directory (cross-map)');
assert(JSON.stringify(cmdOf(act('走到 1000 700'))) === JSON.stringify({ type: 'WALK_TO', mapId: '20010', x: 1000, y: 700 }), '走到 x y');
assert(JSON.stringify(cmdOf(act('接任務 1'))) === JSON.stringify({ type: 'ACCEPT_QUEST', questId: 1 }), '接任務');
assert(JSON.stringify(cmdOf(act('買 50001 3'))) === JSON.stringify({ type: 'BUY_ITEM', itemId: 50001, count: 3 }), '買 id 數量');
assert(JSON.stringify(cmdOf(act('賣 100000'))) === JSON.stringify({ type: 'SELL_ITEM', itemId: 100000, count: 1 }), '賣 id');
const shopName = village.shops[0].goods.find(x => x.name)!;
assert(parseInput(`買 ${shopName.name}`, village).ok, '買 <商品名稱> resolves through the shop list');
assert(parseInput('賣 藥草', village, { inventory: [{ itemId: 7, name: '藥草', count: 2 }] }).ok, '賣 <名稱> resolves through the inventory');
assert(JSON.stringify(cmdOf(act('工作 4'))) === JSON.stringify({ type: 'WORK_ONCE', skillId: 4 }), '工作');
assert(cmdOf(act('逃跑'))?.type === 'BATTLE_FLEE' && cmdOf(act('快照'))?.type === 'REQUEST_SNAPSHOT', '逃跑／快照');
const bctx = { battleId: 5, enemies: [{ slot: 2, id: 'e', name: '土來姆', hp: 3, maxHp: 9 }] };
const atk = parseInput('攻擊', town, bctx);
assert(atk.ok && JSON.stringify(cmdOf(atk.action)) === JSON.stringify({ type: 'BATTLE_ACTION', battleId: 5, action: { kind: 'ATTACK', targetSlot: 2 } }), '攻擊 defaults to the first enemy slot');
assert(!parseInput('攻擊 哥布林', town, bctx).ok, '攻擊 with an unknown target is explained');
const opt = parseInput('選項 接受', town, { dialogOptions: [{ id: 'ACCEPT_QUEST:1', label: '接受任務：新手任務' }] });
assert(opt.ok && (cmdOf(opt.action) as any).optionId === 'ACCEPT_QUEST:1', '選項 <文字> resolves to the option id');
assert(parseInput('策略 逃跑', null).ok && (act('策略 手動', null) as any).strategy === 'MANUAL', '策略');
assert(act('停止導航', null)?.kind === 'NAV_CANCEL', '停止導航');
for (const bad of ['', '飛 天上', '走到 abc', '接任務', '前往', '前往 不存在的人', '對話 不存在的人', '策略 亂來']) {
  assert(!parseInput(bad, town, ctx).ok, `rejects "${bad}" with an explanation`);
}
assert(!parseInput('前往 阿爾', null).ok, 'name lookups need a snapshot or a directory');
const ambiguous = parseInput('對話 阿', village, ctx);
assert(!ambiguous.ok && ambiguous.error.includes('多個'), 'ambiguous names list candidates');
done();
